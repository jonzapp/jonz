-- The server's own work reaches the database through the API's role
-- (docs/specs/api.md, C4b), so it no longer needs Supabase's Data API.
--
-- jonz_api already becomes `authenticated` (the person) for each operation.
-- The engine and the moves' server side (the cron tick, telling people,
-- settling up) ran as the service role through the Data API; now jonz_api
-- becomes `service_role` for those statements instead, in the same
-- transaction (apps/api/lib/db/scope.ts). It is noinherit, so it holds no
-- service-role rights until it sets the role, and people can never set it:
-- only the API's database login can, and C5 lets only the API's addresses
-- reach the database.
grant service_role to jonz_api;
