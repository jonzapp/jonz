/**
 * The sentence for a refusal. `words` is the reader's (their house's kind),
 * English housemates' until each screen passes its own (translation step 7).
 */
export function humanError(
  error: { message?: string; code?: string } | null | undefined,
  words: Words = wordsFor("en", "housemates"),
): string {
  if (!error) return words("errors.other");
  for (const code of CODES) {
    if (error.message?.includes(code)) return words(`errors.${code}`);
  }
  if (error.code === "42501") return words("errors.denied");
  return words("errors.other");
}
